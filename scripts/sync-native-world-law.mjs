import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve, relative } from "node:path";
import { pathToFileURL } from "node:url";

// Build the actual pure gameplay law for the native host. This is source
// distribution, never an alternative reducer or a checkpoint migration.
const worldRoot = resolve(process.cwd());
const sdkRoot = resolve(process.argv[2] ?? "../receiz/packages/receiz-sdk");
const esbuildModule = process.env.WILDZ_NATIVE_LAW_ESBUILD_MODULE;
if (!esbuildModule) throw Error("Set WILDZ_NATIVE_LAW_ESBUILD_MODULE to the installed esbuild module path.");
const esbuild = await import(pathToFileURL(resolve(esbuildModule)).href);
const result = await esbuild.build({
  absWorkingDir: worldRoot, entryPoints: ["src/features/play/wildz-native-world-law.ts"],
  bundle: true, write: false, metafile: true, format: "esm", platform: "neutral", target: "es2022",
  external: ["@receiz/sdk"], mainFields: ["browser", "module", "main"], legalComments: "inline", sourcemap: false
});
const sources = await Promise.all(Object.keys(result.metafile.inputs).sort().map(async path => ({
  path: relative(worldRoot, resolve(worldRoot, path)), sha256: createHash("sha256").update(await readFile(resolve(worldRoot, path))).digest("hex")
})));
const code = result.outputFiles[0].text;
const manifest = { schema: "wildz.native-world-law-source.v128", sourceFiles: sources, bundleSha256: createHash("sha256").update(code).digest("hex") };
const digest = createHash("sha256").update(JSON.stringify(manifest)).digest("hex");
const target = resolve(sdkRoot, "src");
await mkdir(target, { recursive: true });
await writeFile(resolve(target, "wildzNativeWorldLaw.generated.js"), `// Generated by Wildz scripts/sync-native-world-law.mjs.\n${code}`);
await writeFile(resolve(target, "wildzNativeWorldLaw.generated.d.ts"), "export function replayWildzNativeWorldLaw(steps: readonly unknown[]): Readonly<Record<string, unknown>>;\nexport function readWildzNativeWorldCardPayload(bytes: Uint8Array): Readonly<Record<string, unknown>>;\nexport function matchesWildzNativeWorldCardProjection(bytes: Uint8Array, current: unknown): boolean;\n");
await writeFile(resolve(target, "wildzNativeWorldLawManifest.generated.ts"), `// Generated from the complete source dependency graph.\nexport const WILDZ_NATIVE_WORLD_LAW_DIGEST = ${JSON.stringify(digest)};\nexport const WILDZ_NATIVE_WORLD_LAW_SOURCE = ${JSON.stringify(manifest, null, 2)} as const;\n`);
console.log(`Native world law ${digest}: ${sources.length} exact source files, ${Buffer.byteLength(code)} bytes.`);
